data NodeSensors s = NodeSensors
  { batteryVoltage :: !(V s)
  , gridVoltage :: !(V s)
  , loadCurrent :: !(I s)
  , gridCurrent :: !(I s)
  , solarCurrent :: !(I s)
  , temperature :: !s
  } deriving (Eq, Ord, Show, Generic)


newtype NodeAt  s = NodeAt (UTCTime, NodeSensors s) deriving (Eq, Ord, Show, Generic)

instance (Field s) => ToRow (NodeAt s)

-- $ converts an EnergyState autogenerated from a protobuf to a NodeSensors that we control
fromNodeMessage :: NM.EnergyState -> NodeAt R
fromNodeMessage nm = NodeAt (nodeTimeToUTC nm, NodeSensors
                       { batteryVoltage = v $ nm ^. NM.batteryVoltage
                       , gridVoltage = v $ nm ^.  NM.gridVoltage
                       , loadCurrent = i $ nm ^.  NM.batteryToLoadCurrent
                       , gridCurrent = cOut + cIn
                       , solarCurrent = i $ nm ^. NM.solarInputCurrent
                       , temperature = nm ^. NM.temperature
                       })
  where
    cOut :: I R
    cOut = i $ nm ^.  NM.batteryToGridCurrent
    cIn :: I R
    cIn = i $ (-1) P.* (nm ^. NM.gridToBatteryCurrent)



