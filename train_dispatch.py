#!/usr/bin/env python3
"""
Physics-Informed Neural Network Training for AC Power Flow Dispatch

Trains a neural network to predict P,Q setpoints from power generation/load data,
using samples generated by the IPOPT optimal power flow solver.

Two architectures available:

1. Dense Network (default):
   - Simple MLP with physics-informed loss
   - Fast to train, good for small grids

2. Summing Functor Network (--use-functor):
   - Based on Manin-Marcolli categorical framework
   - Outputs edge flows, projects to Kirchhoff equalizer
   - GUARANTEED power balance by construction (no soft penalty needed)
   - Better for larger/complex grids

Key features:
- Outputs P,Q setpoints (what inverters control), not V,δ
- Physics-informed loss: penalizes power balance violations
- MC Dropout: uncertainty quantification at inference time
- Realistic sampling: solar curves, load profiles, weather noise

Usage:
    python train_dispatch.py ac_samples.csv 12 8 --epochs 200
    python train_dispatch.py ac_samples.csv 12 8 --use-functor --epochs 200
    python train_dispatch.py --help

Expected training time:
    Dense: ~30 min on CPU, ~5 min on GPU
    Functor: ~60 min on CPU, ~10 min on GPU

Expected accuracy:
    P setpoint: <0.5 kW RMSE
    Q setpoint: <0.2 kVAR RMSE
"""

